            sprintf(title1,"../Data/SC/SjSk/SjSk_%d_%d_%d_%d_%d_%d_%d_%d_%d.dat",ttt0,ttt1,jjt0,jjt1,N,nup,ndown,ii,jj); //| ==== Name | I;  
